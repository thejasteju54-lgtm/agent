"""Mock AI Model Provider for deterministic testing and offline execution."""

import uuid
from typing import Any, Dict, List, Optional, Type
from pydantic import BaseModel
from personal_ai.agent.task_models import ExecutionPlan, PlanStep, RiskLevel
from personal_ai.models.base import (
    BaseModelProvider,
    ModelResponse,
    ProviderHealth,
)
from personal_ai.tools.registry import ToolDefinition


class MockProvider(BaseModelProvider):
    """Deterministic mock provider returning synthesized responses."""

    provider_name: str = "mock"

    def __init__(self, model_name: str = "mock-agent-v1", available: bool = True):
        self.model_name = model_name
        self.is_available = available

    def health_check(self) -> ProviderHealth:
        return ProviderHealth(
            provider_name=self.provider_name,
            available=self.is_available,
            model_name=self.model_name,
            details="Mock testing provider ready.",
        )

    def generate(
        self,
        prompt: str,
        system_prompt: Optional[str] = None,
        response_format: Optional[Type[BaseModel]] = None,
        temperature: float = 0.2,
    ) -> ModelResponse:
        mock_text = f"Mock response for prompt: '{prompt}'"
        structured = None
        if response_format == ExecutionPlan:
            plan = self.generate_plan(prompt, [])
            structured = plan.model_dump()
            mock_text = plan.model_dump_json()

        return ModelResponse(
            text=mock_text,
            structured_data=structured,
            model_name=self.model_name,
            prompt_tokens=10,
            completion_tokens=20,
        )

    def generate_plan(
        self,
        prompt: str,
        available_tools: List[ToolDefinition],
    ) -> ExecutionPlan:
        t_id = str(uuid.uuid4())
        return ExecutionPlan(
            task_id=t_id,
            prompt=prompt,
            steps=[
                PlanStep(
                    step_id=str(uuid.uuid4()),
                    step_number=1,
                    tool_name="list_directory",
                    description=f"Inspect directory for task: {prompt}",
                    input_params={"path": "."},
                    risk_level=RiskLevel.LOW,
                    requires_approval=False,
                    expected_outcome="Directory listed",
                )
            ],
            assumptions=["Generated by MockProvider."],
            requires_clarification=False,
        )
